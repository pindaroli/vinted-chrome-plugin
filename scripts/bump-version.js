import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const pkgPath = path.join(rootDir, 'package.json');
const manifestPath = path.join(rootDir, 'manifest.json');
const versionTsPath = path.join(rootDir, 'src', 'version.ts');

const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
const currentVersion = pkg.version || '1.0.0';

// Incrementa la versione di patch (SemVer: MAJOR.MINOR.PATCH)
const parts = currentVersion.split('.').map(Number);
if (parts.length === 3 && parts.every(n => !isNaN(n))) {
  parts[2] += 1;
} else if (parts.length > 0 && !isNaN(parts[parts.length - 1])) {
  parts[parts.length - 1] += 1;
} else {
  parts[0] = 1;
  parts[1] = 0;
  parts[2] = 1;
}

const nextVersion = parts.join('.');

// 1. Aggiorna package.json
pkg.version = nextVersion;
fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n', 'utf8');

// 2. Aggiorna manifest.json per Chrome Extension Manifest V3
if (fs.existsSync(manifestPath)) {
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  manifest.version = nextVersion;
  fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n', 'utf8');
}

// 3. Genera src/version.ts per consumo runtime nel Side Panel
const versionTsContent = `// Auto-generated by scripts/bump-version.js on each build. Do not edit manually.
export const APP_VERSION = '${nextVersion}';
export const BUILD_TIMESTAMP = '${new Date().toISOString()}';
`;
fs.writeFileSync(versionTsPath, versionTsContent, 'utf8');

console.log(`[Version Bump] Version incremented: ${currentVersion} -> ${nextVersion}`);
